// Builds src/data/terrain-atlas.json from public/assets/tiles/dtef/<set>/ (original DTEF atlases, private build, #178).
// A tile id is segment*48 + slot: segment 0 wall, 1 second terrain, 2 floor; slot = row*6 + column (6 x 8 grid of 24 px).
// Run: node tools/build-dtef-index.mjs   (add --check to compare with the committed file instead of writing it)
import fs from 'node:fs';
import {readPng} from './png-read.mjs';
const SETS = {moss: 'TinyWoods', wet: 'WaterfallCave', ash: 'MagmaCavern2'};
const dir = new URL('../public/assets/tiles/dtef/', import.meta.url);
const tileEmpty = (img, id) => {
  const seg = Math.floor(id / 48), slot = id % 48, x0 = seg * 144 + (slot % 6) * 24, y0 = Math.floor(slot / 6) * 24;
  for (let y = 0; y < 24; y++) for (let x = 0; x < 24; x++) if (img.data[((y0 + y) * img.width + x0 + x) * 4 + 3] > 0) return false;
  return true;
};
const themes = {};
for (const [theme, set] of Object.entries(SETS)) {
  const files = fs.readdirSync(new URL(set + '/', dir)).sort();
  const variants = [];
  for (let v = 0; files.includes(`tileset_${v}.png`); v++) {
    const img = readPng(new URL(`${set}/tileset_${v}.png`, dir));
    if (img.width !== 432 || img.height !== 192) throw new Error(`${set} tileset_${v}.png is ${img.width}x${img.height}`);
    variants.push({file: `tileset_${v}.png`, empty: Array.from({length: 144}, (_, i) => i).filter((i) => tileEmpty(img, i))});
  }
  const groups = new Map();
  for (const f of files) {
    const m = /^tileset_(\d+)_frame(\d+)_(\d+)\.(\d+)\.png$/.exec(f);
    if (!m) continue;
    const key = `${m[1]}/${m[2]}`, g = groups.get(key) ?? {variant: +m[1], layer: +m[2], ticks: +m[4], frames: []};
    if (g.ticks !== +m[4]) throw new Error('mixed durations in ' + key);
    g.frames[+m[3]] = {file: f}; groups.set(key, g);
  }
  const animations = [];
  for (const g of [...groups.values()].sort((a, b) => a.variant - b.variant || a.layer - b.layer)) {
    if (g.frames.some((f) => !f)) throw new Error(`${set}: missing frame number in layer ${g.layer}`);
    let tiles = null;
    for (const f of g.frames) {
      const img = readPng(new URL(`${set}/${f.file}`, dir));
      const live = Array.from({length: 144}, (_, i) => i).filter((i) => !tileEmpty(img, i));
      tiles = tiles ? tiles.filter((i) => live.includes(i)) : live;
    }
    animations.push({variant: g.variant, layer: g.layer, ticks: g.ticks, frames: g.frames.map((f) => f.file), tiles});
  }
  themes[theme] = {set, variants, animations};
}
const out = JSON.stringify({
  note: 'Generated by tools/build-dtef-index.mjs. Tile id = segment*48 + slot (segment 0 wall, 1 second terrain, 2 floor). ticks are 1/60 s.',
  defaultSource: 'dtef',
  variantZeroShare: 0.95,
  themes,
}, null, 1) + '\n';
const target = new URL('../src/data/terrain-atlas.json', import.meta.url);
if (process.argv.includes('--check')) { if (fs.readFileSync(target, 'utf8') !== out) { console.error('terrain-atlas.json is out of date'); process.exit(1); } }
else fs.writeFileSync(target, out);
