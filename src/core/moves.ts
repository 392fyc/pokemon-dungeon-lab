/** Official move reach, target and effect data for the current private trial. */
import source from '../data/pmd-moves.json' with {type:'json'};

export type MoveRange='front'|'front2'|'line10'|'around'|'room'|'user';
export type MoveTarget='enemy'|'user'|'teammates'|'party'|'all';
export type MoveSpec={
  range:MoveRange;
  target:MoveTarget;
  power:number|null;
  effects:string[];
  source?:string;
  game?:string;
  gameName?:string;
  note?:string;
  official?:Record<string,string>;
};

type MoveData={moves:Record<string,MoveSpec>};
/** The mutable table is exported so focused tests can inject a synthetic range/effect and restore it afterward. */
export const MOVE_DEFS:Record<string,MoveSpec>=Object.assign(Object.create(null), (source as unknown as MoveData).moves);
export function moveOf(id:string):MoveSpec|undefined {
  return Object.prototype.hasOwnProperty.call(MOVE_DEFS,id)?MOVE_DEFS[id]:undefined;
}

/** Categories come from the fixed Showdown snapshot, independently of move reach. */
export type MoveCategory='Physical'|'Special'|'Status';
const categories:Record<string,MoveCategory>=(source as unknown as {categories:Record<string,MoveCategory>}).categories;
export function moveCategory(id:string):MoveCategory|undefined {
  return Object.prototype.hasOwnProperty.call(categories,id)?categories[id]:undefined;
}

/** 8.8 (#165): hit chance, secondary effects, self cost and thaw flag per move; generated by tools/data/import_move_effects.py. */
import effectSource from '../data/move-effects.json' with {type:'json'};
export type StageKey='atk'|'def'|'spa'|'spd'|'spe'|'acc'|'eva';
export type StageChange=Partial<Record<StageKey,number>>;
export type StatusId='psn'|'tox'|'brn'|'par'|'frz'|'slp'|'nap'|'recharge'|'confusion'|'flinch';
export type MoveFx={chance:number;status?:StatusId;foe?:StageChange;self?:StageChange};
export type MoveEffects={acc:number|null;fx?:MoveFx[];cost?:StageChange;thaw?:true;recoil?:[number,number];powder?:true};
const effects:Record<string,MoveEffects>=(effectSource as unknown as {moves:Record<string,MoveEffects>}).moves;
/** Undefined for ids with no data (the removed Tera Blast, and test-injected moves). */
export function moveEffects(id:string):MoveEffects|undefined {
  return Object.prototype.hasOwnProperty.call(effects,id)?effects[id]:undefined;
}
