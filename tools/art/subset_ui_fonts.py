#!/usr/bin/env python3
"""Build the two OFL UI font subsets. Run only in the project's ignored font venv."""
import argparse
import hashlib
import importlib.metadata
import json
import unicodedata
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
COMMIT = "24ddc1f324cac5d9f5aedca126d298f56e3f1640"
SOURCES = [
    ("body", "NotoSansSC.ttf", "pdl-sans-sc.woff2", "PDL Sans SC", "notosanssc/NotoSansSC[wght].ttf",
     "a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da", "NotoSansSC-OFL.txt"),
    ("display", "ZCOOLQingKeHuangYou-Regular.ttf", "pdl-display.woff2", "PDL Display",
     "zcoolqingkehuangyou/ZCOOLQingKeHuangYou-Regular.ttf",
     "54f0c0df4308cd74cd0f2fd3494ae054dbc4a1fd6fa7d71f4807eb4cdd8b4136", "ZCOOLQingKeHuangYou-OFL.txt"),
]
def sha(data):
    return hashlib.sha256(data).hexdigest()
def ranges(values):
    result = []
    for cp in sorted(values):
        if result and cp == result[-1][1] + 1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return ",".join("U+%X" % a + ("-%X" % b if b != a else "") for a, b in result)
def gb2312_level_one():
    chars = set()
    for hi in range(0xB0, 0xD8):
        for lo in range(0xA1, 0xFF):
            try:
                chars.add(ord(bytes([hi, lo]).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    assert len(chars) == 3755
    return chars
def rename(font, family):
    compact = family.replace(" ", "")
    values = {1: family, 2: "Regular", 3: family + " subset", 4: family, 6: compact + "-Regular",
              16: family, 17: "Regular", 25: compact}
    for rec in list(font["name"].names):
        if rec.nameID in values:
            font["name"].setName(values[rec.nameID], rec.nameID, rec.platformID, rec.platEncID, rec.langID)
    for key, value in values.items():
        font["name"].setName(value, key, 3, 1, 0x409)
    # The copyright and complete OFL remain untouched. No primary name uses Noto's RFN "Source".
    assert all("Source" not in rec.toUnicode() for rec in font["name"].names if rec.nameID in values)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", required=True, type=Path)
    parser.add_argument("--characters", required=True, type=Path)
    args = parser.parse_args()
    expected = dict(line.strip().split("==") for line in
                    (ROOT / "tools/art/requirements-fonts.txt").read_text().splitlines() if line.strip())
    for package, version in expected.items():
        if importlib.metadata.version(package) != version:
            raise SystemExit("Use the pinned task venv: " + package + "==" + version)
    chars = json.loads(args.characters.read_text(encoding="utf-8"))
    target = ROOT / "public/assets/fonts"
    target.mkdir(parents=True, exist_ok=True)
    manifest_path = ROOT / "public/assets/manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    coverage = {"format": 1, "tools": expected, "selection": chars["policy"],
                "gb2312LevelOneCount": 3755, "faces": {}}
    common = set(range(32, 127)) | set(range(0x2000, 0x2070)) | set(range(0x3000, 0x3040))
    common = {cp for cp in common if not unicodedata.category(chr(cp)).startswith("C")}
    css = ["/* Generated by tools/art/subset_ui_fonts.py; do not hand-edit glyph ranges. */"]
    for role, source_name, output_name, family, source_path, digest, license_file in SOURCES:
        source = args.source_dir / source_name
        original = source.read_bytes()
        if sha(original) != digest:
            raise SystemExit("Source font digest mismatch: " + source_name)
        font = TTFont(source, recalcTimestamp=False)
        original_map = set(font.getBestCmap())
        requested = set(chars[role]) | common
        if role == "body":
            requested |= gb2312_level_one()
        options = subset.Options()
        options.flavor = "woff2"
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        options.layout_features = ["*"]
        options.recalc_timestamp = False
        options.notdef_glyph = True
        options.notdef_outline = True
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=requested)
        sub.subset(font)
        rename(font, family)
        font.flavor = "woff2"
        output = target / output_name
        font.save(output)
        verified = TTFont(output, recalcTimestamp=False)
        supported = set(verified.getBestCmap())
        assert requested & original_map <= supported
        axes = {a.axisTag: {"min": a.minValue, "default": a.defaultValue, "max": a.maxValue}
                for a in verified["fvar"].axes} if "fvar" in verified else {}
        if role == "body":
            assert "wght" in axes and axes["wght"]["min"] <= 500 and axes["wght"]["max"] >= 900
        data = output.read_bytes()
        info = {"file": "fonts/" + output_name, "bytes": len(data), "sha256": sha(data),
                "family": family, "codepoints": sorted(supported),
                "systemFallbackCodepoints": sorted(requested - original_map), "axes": axes}
        coverage["faces"][role] = info
        manifest["files"].pop("fonts/" + source_name, None)
        manifest["files"]["fonts/" + output_name] = {
            "bytes": len(data), "sha256": sha(data), "source": "google/fonts", "commit": COMMIT,
            "sourcePath": "ofl/" + source_path, "sourceSha256": digest,
            "licence": "SIL Open Font License 1.1; full copyright and license: fonts/" + license_file,
            "subset": {"family": family, "unicodeRange": ranges(requested),
                       "coverage": "fonts/coverage.json#" + role, "tools": expected,
                       "selection": chars["policy"],
                       "gb2312LevelOneCount": 3755 if role == "body" else 0,
                       "command": "node tools/art/font-characters.mjs <characters.json> && "
                                  "<font-venv-python> tools/art/subset_ui_fonts.py "
                                  "--source-dir <verified-original-font-cache> --characters <characters.json>"}}
        alias = "Noto Sans SC" if role == "body" else "ZCOOL QingKe HuangYou"
        weight = "100 900" if role == "body" else "400"
        css.append('@font-face{font-family:"' + alias + '";font-style:normal;font-weight:' + weight +
                   ';font-display:swap;src:url("/assets/fonts/' + output_name +
                   '") format("woff2");unicode-range:' + ranges(supported) + '}')
        print(json.dumps({"role": role, "bytes": len(data), "glyphCodepoints": len(supported),
                          "systemFallback": len(info["systemFallbackCodepoints"]), "axes": axes}))
    total = sum(face["bytes"] for face in coverage["faces"].values())
    if total > 5_000_000:
        raise SystemExit("Report the actual font size to main before delivery: " + str(total))
    coverage_path = target / "coverage.json"
    coverage_path.write_text(json.dumps(coverage, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    coverage_data = coverage_path.read_bytes()
    manifest["files"]["fonts/coverage.json"] = {
        "bytes": len(coverage_data), "sha256": sha(coverage_data),
        "source": "Generated by tools/art/subset_ui_fonts.py from the verified subset cmap tables",
        "sourcePath": "tools/art/subset_ui_fonts.py",
        "licence": "Project coverage metadata; the adjacent font software remains under SIL OFL 1.1."}
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    css.append(':root{--ui-body:"Noto Sans SC","Microsoft YaHei",sans-serif;'
               '--ui-display:"ZCOOL QingKe HuangYou","Noto Sans SC","Microsoft YaHei",sans-serif}')
    (ROOT / "src/render/fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps({"totalBytes": total, "limitBytes": 5_000_000}))

if __name__ == "__main__":
    main()
